# Переменная
num = 16
# = - оператор присваивания

# Присваивание нескольким переменным одного значения
num1 = num2 = 0
# Присваивание нескольким переменным разных значений
num3, num4 = 10, 20
# SWAP
num3, num4 = num4, num3

# Нотации - правила оформления названий переменных
# snake_case - age_of_client
# camelCase - clientAge, ageOfClient
# PascalCase - ClientAge, AgeOfClient

# Правила алфавита для названия переменных
# Можно использовать: a-z, A-Z, 0-9, _